// impact: "availability" marks a Direct entry whose Global-Admin-level effect is
//   locking everyone out (a ransom vector), not gaining Global Admin's privileges.
// Roles carry templateId (Microsoft's role template GUID) so GUID-only exports and
//   GDAP relationships resolve; the engine builds its lookup from these.
// Engine edges (read by the tenant engine; never hardcode names in app.js):
//   plantsCredentials: "any" | "owned"  can add a credential to any app / apps it owns
//   selfEscalates: true                 can grant itself a Direct permission, no tenant dependency
//   writesOpenGroups: true              can change membership of non-role-assignable groups
// tier: 1 = tenant-takeover class, 2 = broad data / sensitive, 3 = scoped
// guid: Graph appRoleId where known, so exports carrying only GUIDs still match.
